use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Language {
    #[default]
    Turkish,
    English,
    German,
    Spanish,
}

#[allow(dead_code)]
impl Language {
    pub fn all() -> &'static [Language] {
        &[Language::Turkish, Language::English, Language::German, Language::Spanish]
    }

    pub fn display_name(&self) -> &'static str {
        match self {
            Language::Turkish => "Türkçe",
            Language::English => "English",
            Language::German => "Deutsch",
            Language::Spanish => "Español",
        }
    }

    pub fn code(&self) -> &'static str {
        match self {
            Language::Turkish => "tr",
            Language::English => "en",
            Language::German => "de",
            Language::Spanish => "es",
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code {
            "en" => Language::English,
            "de" => Language::German,
            "es" => Language::Spanish,
            _ => Language::Turkish,
        }
    }
}

